#!/usr/bin/env python3
"""Bake a Vial keyboard definition into a C header.

    vial_definition.py <vial.json> <uid: 16 hex digits> <unlock rows> <unlock cols>

Unlock rows/cols are comma-separated matrix positions, paired up ("0,3" and
"0,13" = keys (0,0) and (3,13)). They are emitted here rather than passed as
-D defines because SDCC mangles a define whose value holds braces and commas.

Vial GUI fetches the definition from the keyboard (Vial command 0x01 size,
0x02 32-byte pages) and runs `lzma.decompress()` + `json.loads()` on it. The
compression call is the one vial-qmk's util/vial_generate_definition.py uses --
XZ container, library defaults -- so the GUI sees exactly what it expects.

The array lands in CODE space (`__code`): it is only ever read by the page
handler, never copied to XDATA, so it costs flash and no RAM.
"""

import json
import lzma
import sys


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)

    path, uid_hex = sys.argv[1], sys.argv[2]
    uid = bytes.fromhex(uid_hex)
    if len(uid) != 8:
        sys.exit('vial_definition.py: the keyboard UID must be exactly 8 bytes (16 hex digits)')

    rows = [int(v) for v in sys.argv[3].split(',') if v.strip()]
    cols = [int(v) for v in sys.argv[4].split(',') if v.strip()]
    if not rows or len(rows) != len(cols) or len(rows) > 14:
        sys.exit('vial_definition.py: need 1..14 unlock keys, as matching row and column lists')

    with open(path, encoding='utf-8') as f:
        definition = json.load(f)

    minified = json.dumps(definition, separators=(',', ':')).strip()
    payload = lzma.compress(minified.encode('utf-8'))

    out = sys.stdout
    out.write('#pragma once\n')
    out.write('/* Generated by utils/vial_definition.py from {} -- do not edit. */\n'.format(path))
    out.write('#include <stdint.h>\n\n')
    out.write('#define VIAL_KEYBOARD_UID {{{}}}\n\n'.format(', '.join('0x{:02X}'.format(b) for b in uid)))
    out.write('#define VIAL_UNLOCK_ROWS {{{}}}\n'.format(', '.join(str(r) for r in rows)))
    out.write('#define VIAL_UNLOCK_COLS {{{}}}\n\n'.format(', '.join(str(c) for c in cols)))
    out.write('#define VIAL_DEFINITION_SIZE {}u\n\n'.format(len(payload)))
    out.write('static const __code uint8_t vial_definition[VIAL_DEFINITION_SIZE] = {\n')
    for i in range(0, len(payload), 16):
        out.write('    ' + ', '.join('0x{:02X}'.format(b) for b in payload[i:i + 16]) + ',\n')
    out.write('};\n')


if __name__ == '__main__':
    main()
